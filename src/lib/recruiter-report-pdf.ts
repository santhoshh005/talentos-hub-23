import { jsPDF } from "jspdf";
import autoTable from "jspdf-autotable";
import type { PipelineResult } from "./pipeline.functions";

// TalentOS branded PDF export for the Recruiter Intelligence Report.
// Reuses the existing pipeline result — no re-computation, no AI calls.
// Designed to be modular: additional sections (Interview Questions,
// Salary Benchmark, Recruiter Notes, Career Progression) can be
// appended by calling the exported section helpers with new data.

const COLOR = {
  bg: "#020617",
  ink: "#0F172A",
  primary: "#2563EB",
  accent: "#38BDF8",
  sub: "#475569",
  muted: "#94A3B8",
  line: "#E2E8F0",
  soft: "#F1F5F9",
  white: "#FFFFFF",
  good: "#16A34A",
  warn: "#D97706",
  bad: "#DC2626",
};

const PAGE = { w: 210, h: 297, margin: 15 };
const CONTENT_W = PAGE.w - PAGE.margin * 2;
const VERSION = "1.0.0";

type Ctx = { pdf: jsPDF; y: number };

function rgb(hex: string): [number, number, number] {
  return [
    parseInt(hex.slice(1, 3), 16),
    parseInt(hex.slice(3, 5), 16),
    parseInt(hex.slice(5, 7), 16),
  ];
}
function setFill(pdf: jsPDF, hex: string) { pdf.setFillColor(...rgb(hex)); }
function setText(pdf: jsPDF, hex: string) { pdf.setTextColor(...rgb(hex)); }
function setDraw(pdf: jsPDF, hex: string) { pdf.setDrawColor(...rgb(hex)); }

function ensure(c: Ctx, needed: number) {
  if (c.y + needed > PAGE.h - 20) {
    c.pdf.addPage();
    c.y = PAGE.margin + 8;
  }
}

function newPage(c: Ctx) {
  c.pdf.addPage();
  c.y = PAGE.margin + 8;
}

function scoreColor(v: number) {
  if (v >= 75) return COLOR.good;
  if (v >= 55) return COLOR.warn;
  return COLOR.bad;
}

function recommendationFor(pct: number) {
  if (pct >= 85) return { label: "Highly Recommended", color: COLOR.good };
  if (pct >= 70) return { label: "Recommended", color: COLOR.primary };
  if (pct >= 50) return { label: "Needs Review", color: COLOR.warn };
  return { label: "Low Match", color: COLOR.bad };
}

function drawHeader(pdf: jsPDF, candidate: string) {
  setFill(pdf, COLOR.ink);
  pdf.rect(0, 0, PAGE.w, 14, "F");
  setFill(pdf, COLOR.accent);
  pdf.circle(PAGE.margin + 3, 7, 2.2, "F");
  setText(pdf, COLOR.white);
  pdf.setFont("helvetica", "bold");
  pdf.setFontSize(10);
  pdf.text("TalentOS", PAGE.margin + 8, 8.4);
  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(8);
  setText(pdf, COLOR.muted);
  pdf.text("Recruiter Intelligence Report", PAGE.margin + 28, 8.4);
  setText(pdf, COLOR.white);
  pdf.text(candidate, PAGE.w - PAGE.margin, 8.4, { align: "right" });
}

function drawFooters(pdf: jsPDF, timestamp: string) {
  const total = pdf.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    pdf.setPage(i);
    setDraw(pdf, COLOR.line);
    pdf.setLineWidth(0.2);
    pdf.line(PAGE.margin, PAGE.h - 12, PAGE.w - PAGE.margin, PAGE.h - 12);
    setText(pdf, COLOR.muted);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8);
    pdf.text(
      `Generated by TalentOS Resume Intelligence Platform  •  ${timestamp}  •  v${VERSION}`,
      PAGE.margin,
      PAGE.h - 7,
    );
    pdf.text(`Page ${i} of ${total}`, PAGE.w - PAGE.margin, PAGE.h - 7, { align: "right" });
  }
}

function sectionTitle(c: Ctx, eyebrow: string, title: string) {
  ensure(c, 18);
  setText(c.pdf, COLOR.muted);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(8);
  c.pdf.text(eyebrow.toUpperCase(), PAGE.margin, c.y);
  c.y += 4;
  setText(c.pdf, COLOR.ink);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(16);
  c.pdf.text(title, PAGE.margin, c.y + 4);
  c.y += 8;
  setDraw(c.pdf, COLOR.line);
  c.pdf.setLineWidth(0.3);
  c.pdf.line(PAGE.margin, c.y, PAGE.margin + 30, c.y);
  c.y += 6;
}

function paragraph(c: Ctx, text: string, size = 10, color = COLOR.sub) {
  if (!text) return;
  c.pdf.setFont("helvetica", "normal");
  c.pdf.setFontSize(size);
  setText(c.pdf, color);
  const lines = c.pdf.splitTextToSize(text, CONTENT_W) as string[];
  const h = lines.length * (size * 0.45) + 2;
  ensure(c, h);
  c.pdf.text(lines, PAGE.margin, c.y + size * 0.4);
  c.y += h;
}

function bullets(c: Ctx, items: string[]) {
  if (!items?.length) { paragraph(c, "Not Found", 10, COLOR.muted); return; }
  c.pdf.setFont("helvetica", "normal");
  c.pdf.setFontSize(10);
  for (const item of items) {
    if (!item) continue;
    const lines = c.pdf.splitTextToSize(item, CONTENT_W - 6) as string[];
    const h = lines.length * 4.4 + 1.5;
    ensure(c, h);
    setText(c.pdf, COLOR.primary);
    c.pdf.text("•", PAGE.margin, c.y + 4);
    setText(c.pdf, COLOR.ink);
    c.pdf.text(lines, PAGE.margin + 4, c.y + 4);
    c.y += h;
  }
}

function keyValueGrid(c: Ctx, entries: [string, string][]) {
  const colW = CONTENT_W / 2;
  const rowH = 13;
  for (let i = 0; i < entries.length; i += 2) {
    ensure(c, rowH);
    const row = [entries[i], entries[i + 1]].filter(Boolean) as [string, string][];
    row.forEach(([k, v], idx) => {
      const x = PAGE.margin + idx * colW;
      setFill(c.pdf, COLOR.soft);
      c.pdf.roundedRect(x, c.y, colW - 4, rowH - 2, 1.5, 1.5, "F");
      setText(c.pdf, COLOR.muted);
      c.pdf.setFont("helvetica", "bold");
      c.pdf.setFontSize(7.5);
      c.pdf.text(k.toUpperCase(), x + 3, c.y + 4);
      setText(c.pdf, COLOR.ink);
      c.pdf.setFont("helvetica", "normal");
      c.pdf.setFontSize(10);
      const val = v || "Not Found";
      const lines = c.pdf.splitTextToSize(val, colW - 8) as string[];
      c.pdf.text(lines.slice(0, 1), x + 3, c.y + 9);
    });
    c.y += rowH;
  }
}

function skillTable(c: Ctx, title: string, items: string[], tone: string) {
  ensure(c, 14);
  setText(c.pdf, COLOR.ink);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(11);
  c.pdf.text(`${title}  (${items.length})`, PAGE.margin, c.y);
  c.y += 3;
  if (!items.length) {
    paragraph(c, "None", 10, COLOR.muted);
    return;
  }
  // Build a 3-column table of skill chips
  const cols = 3;
  const rows: string[][] = [];
  for (let i = 0; i < items.length; i += cols) {
    const row = items.slice(i, i + cols);
    while (row.length < cols) row.push("");
    rows.push(row);
  }
  autoTable(c.pdf, {
    startY: c.y,
    body: rows,
    theme: "grid",
    margin: { left: PAGE.margin, right: PAGE.margin },
    styles: {
      font: "helvetica",
      fontSize: 9,
      cellPadding: 2.5,
      textColor: rgb(COLOR.ink),
      lineColor: rgb(COLOR.line),
      lineWidth: 0.15,
      overflow: "linebreak",
    },
    bodyStyles: { fillColor: rgb(tone === COLOR.good ? "#ECFDF5" : tone === COLOR.bad ? "#FEF2F2" : "#EFF6FF") },
    columnStyles: {
      0: { cellWidth: CONTENT_W / 3 },
      1: { cellWidth: CONTENT_W / 3 },
      2: { cellWidth: CONTENT_W / 3 },
    },
    didParseCell: (data) => {
      if (data.cell.raw === "") {
        data.cell.styles.fillColor = rgb(COLOR.white);
      }
    },
  });
  // @ts-expect-error - lastAutoTable added at runtime
  c.y = c.pdf.lastAutoTable.finalY + 6;
}

function coverPage(
  c: Ctx,
  meta: { candidate: string; role: string; domain: string; matchPct: number; analysisId: string; generatedAt: string },
) {
  const { candidate, role, domain, matchPct, analysisId, generatedAt } = meta;
  c.y = 40;
  // Brand logo mark
  setFill(c.pdf, COLOR.primary);
  c.pdf.roundedRect(PAGE.margin, c.y, 14, 14, 3, 3, "F");
  setText(c.pdf, COLOR.white);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(11);
  c.pdf.text("T", PAGE.margin + 5.2, c.y + 9.5);
  setText(c.pdf, COLOR.ink);
  c.pdf.setFontSize(22);
  c.pdf.text("TalentOS", PAGE.margin + 18, c.y + 10);
  setText(c.pdf, COLOR.muted);
  c.pdf.setFont("helvetica", "normal");
  c.pdf.setFontSize(9);
  c.pdf.text("AI Recruitment Intelligence Platform", PAGE.margin + 18, c.y + 15);
  c.y += 30;

  setText(c.pdf, COLOR.muted);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(9);
  c.pdf.text("RECRUITER INTELLIGENCE REPORT", PAGE.margin, c.y);
  c.y += 8;
  setText(c.pdf, COLOR.ink);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(30);
  const nameLines = c.pdf.splitTextToSize(candidate, CONTENT_W) as string[];
  c.pdf.text(nameLines, PAGE.margin, c.y + 8);
  c.y += nameLines.length * 10 + 4;

  setText(c.pdf, COLOR.sub);
  c.pdf.setFont("helvetica", "normal");
  c.pdf.setFontSize(12);
  c.pdf.text(`${role}  •  ${domain}`, PAGE.margin, c.y + 6);
  c.y += 16;

  // Score card
  const cardH = 60;
  setFill(c.pdf, COLOR.soft);
  c.pdf.roundedRect(PAGE.margin, c.y, CONTENT_W, cardH, 3, 3, "F");

  // Donut
  const cx = PAGE.margin + 30;
  const cy = c.y + cardH / 2;
  const r = 22;
  setDraw(c.pdf, "#E2E8F0");
  c.pdf.setLineWidth(5);
  c.pdf.circle(cx, cy, r, "S");
  // Approximate arc using multiple short segments
  const pct = Math.max(0, Math.min(100, matchPct)) / 100;
  const segs = Math.max(1, Math.round(60 * pct));
  setDraw(c.pdf, scoreColor(matchPct));
  c.pdf.setLineWidth(5);
  for (let i = 0; i < segs; i++) {
    const a1 = -Math.PI / 2 + (i / 60) * Math.PI * 2;
    const a2 = -Math.PI / 2 + ((i + 1) / 60) * Math.PI * 2;
    c.pdf.line(cx + Math.cos(a1) * r, cy + Math.sin(a1) * r, cx + Math.cos(a2) * r, cy + Math.sin(a2) * r);
  }
  setText(c.pdf, COLOR.ink);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(16);
  c.pdf.text(`${matchPct}%`, cx, cy + 2, { align: "center" });
  setText(c.pdf, COLOR.muted);
  c.pdf.setFontSize(7);
  c.pdf.text("MATCH", cx, cy + 7, { align: "center" });

  // Recommendation
  const rec = recommendationFor(matchPct);
  const rx = PAGE.margin + 65;
  const ry = c.y + 14;
  setText(c.pdf, COLOR.muted);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(8);
  c.pdf.text("RECOMMENDATION", rx, ry);
  setFill(c.pdf, rec.color);
  const label = rec.label.toUpperCase();
  c.pdf.setFontSize(9);
  const w = c.pdf.getTextWidth(label) + 8;
  c.pdf.roundedRect(rx, ry + 3, w, 8, 2, 2, "F");
  setText(c.pdf, COLOR.white);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.text(label, rx + 4, ry + 8.5);
  setText(c.pdf, COLOR.sub);
  c.pdf.setFont("helvetica", "normal");
  c.pdf.setFontSize(9);
  c.pdf.text(`Overall Match Score: ${matchPct}%`, rx, ry + 20);
  c.pdf.text(`Detected Role: ${role}`, rx, ry + 26);
  c.pdf.text(`Detected Domain: ${domain}`, rx, ry + 32);

  c.y += cardH + 10;

  // Meta
  keyValueGrid(c, [
    ["Generated", generatedAt],
    ["Analysis ID", analysisId],
  ]);
}

function executiveSummaryPage(c: Ctx, text: string, followUps: string[]) {
  newPage(c);
  sectionTitle(c, "Section 1", "Executive Summary");
  paragraph(c, text, 11, COLOR.ink);
  c.y += 4;
  if (followUps.length) {
    setText(c.pdf, COLOR.muted);
    c.pdf.setFont("helvetica", "bold");
    c.pdf.setFontSize(9);
    c.pdf.text("KEY HIGHLIGHTS", PAGE.margin, c.y);
    c.y += 5;
    bullets(c, followUps);
  }
}

function candidateProfilePage(c: Ctx, resume: any) {
  newPage(c);
  sectionTitle(c, "Section 2", "Candidate Profile");
  keyValueGrid(c, [
    ["Email", resume.email],
    ["Phone", resume.phone],
    ["Location", resume.location],
    ["Notice Period", resume.noticePeriod],
    ["Experience", resume.experience],
    ["Relevant Experience", resume.relevantExperience],
    ["Current Designation", resume.currentDesignation],
    ["Current Company", resume.currentCompany],
  ]);
  c.y += 4;

  setText(c.pdf, COLOR.ink);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(11);
  ensure(c, 8);
  c.pdf.text("Education", PAGE.margin, c.y); c.y += 3;
  bullets(c, resume.educationHistory?.length ? resume.educationHistory : [resume.education]);

  ensure(c, 8);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(11);
  c.pdf.text("Certifications", PAGE.margin, c.y); c.y += 3;
  bullets(c, resume.certifications);

  ensure(c, 8);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(11);
  c.pdf.text("Employment History", PAGE.margin, c.y); c.y += 3;
  bullets(c, resume.employmentHistory);

  ensure(c, 8);
  c.pdf.setFont("helvetica", "bold");
  c.pdf.setFontSize(11);
  c.pdf.text("Projects", PAGE.margin, c.y); c.y += 3;
  bullets(c, resume.projects);
}

function skillAnalysisPage(c: Ctx, matching: any) {
  newPage(c);
  sectionTitle(c, "Section 3", "Skill Analysis");
  skillTable(c, "Matching Skills", matching.matchingSkills.map((m: any) => m.skill), COLOR.good);
  skillTable(c, "Missing Skills", matching.missingSkills, COLOR.bad);
  skillTable(c, "Additional Skills", matching.additionalSkills, COLOR.accent);
}

function evidenceAnalysisPage(c: Ctx, evidence: any[]) {
  newPage(c);
  sectionTitle(c, "Section 4", "Evidence Analysis");
  if (!evidence.length) { paragraph(c, "No evidence available.", 10, COLOR.muted); return; }
  autoTable(c.pdf, {
    startY: c.y,
    head: [["Skill", "Strength", "Found In", "Occurrences", "Years"]],
    body: evidence.map((e) => [
      e.skill,
      `${Math.round(e.evidenceStrength)}%`,
      (e.foundIn || []).join(", ") || "—",
      String(e.occurrenceCount ?? 0),
      String(e.yearsReferenced ?? 0),
    ]),
    theme: "striped",
    margin: { left: PAGE.margin, right: PAGE.margin },
    headStyles: { fillColor: rgb(COLOR.ink), textColor: rgb(COLOR.white), fontStyle: "bold", fontSize: 9 },
    styles: { font: "helvetica", fontSize: 9, cellPadding: 2.5, textColor: rgb(COLOR.ink), overflow: "linebreak" },
    alternateRowStyles: { fillColor: rgb(COLOR.soft) },
    columnStyles: {
      0: { cellWidth: 45, fontStyle: "bold" },
      1: { cellWidth: 22, halign: "center" },
      2: { cellWidth: 65 },
      3: { cellWidth: 25, halign: "center" },
      4: { cellWidth: 20, halign: "center" },
    },
  });
  // @ts-expect-error runtime
  c.y = c.pdf.lastAutoTable.finalY + 6;
}

const STAGE_LABELS: Record<string, string> = {
  resumeParser: "Resume Parser",
  jdIntelligence: "JD Intelligence",
  skillNormalization: "Skill Normalizer",
  matching: "Matching Engine",
  evidence: "Evidence Engine",
};

function pipelineTransparencyPage(c: Ctx, metadata: any) {
  newPage(c);
  sectionTitle(c, "Section 5", "Pipeline Transparency");
  autoTable(c.pdf, {
    startY: c.y,
    head: [["Stage", "Execution Time", "Status"]],
    body: metadata.stages.map((s: any) => [
      STAGE_LABELS[s.stage] || s.stage,
      `${Math.round(s.durationMs)} ms`,
      s.ok ? "OK" : "Failed",
    ]),
    theme: "grid",
    margin: { left: PAGE.margin, right: PAGE.margin },
    headStyles: { fillColor: rgb(COLOR.ink), textColor: rgb(COLOR.white), fontStyle: "bold" },
    styles: { font: "helvetica", fontSize: 10, cellPadding: 3, textColor: rgb(COLOR.ink) },
    columnStyles: {
      0: { cellWidth: 90, fontStyle: "bold" },
      1: { cellWidth: 45, halign: "center" },
      2: { cellWidth: 45, halign: "center" },
    },
    didParseCell: (data) => {
      if (data.section === "body" && data.column.index === 2) {
        const ok = data.cell.raw === "OK";
        data.cell.styles.textColor = rgb(ok ? COLOR.good : COLOR.bad);
        data.cell.styles.fontStyle = "bold";
      }
    },
  });
  // @ts-expect-error runtime
  c.y = c.pdf.lastAutoTable.finalY + 6;
  setText(c.pdf, COLOR.muted);
  c.pdf.setFont("helvetica", "normal");
  c.pdf.setFontSize(9);
  c.pdf.text(
    `Pipeline v${metadata.version}  •  Total: ${Math.round(metadata.totalDurationMs)} ms`,
    PAGE.margin,
    c.y,
  );
}

/* ---------------- Public API ---------------- */

export function buildRecruiterReportFileName(candidate: string, date = new Date()): string {
  const safe = (candidate || "Candidate").replace(/[^A-Za-z0-9]+/g, "_").replace(/^_|_$/g, "") || "Candidate";
  const iso = date.toISOString().slice(0, 10);
  return `TalentOS_Report_${safe}_${iso}.pdf`;
}

export function generateRecruiterReportPdf(result: PipelineResult): jsPDF {
  if (!result.ok) {
    throw new Error("No report available to export.");
  }
  const { resume, jobDescription, matching, evidence, metadata } = result;
  const matchPct = Math.round(
    (matching.similarity.matchedRequiredSkills / (matching.similarity.totalRequiredSkills || 1)) * 100,
  );
  const generatedAt = new Date().toLocaleString();
  const analysisId = `TOS-${new Date(metadata.startedAt).getTime().toString(36).toUpperCase()}`;

  const pdf = new jsPDF({ unit: "mm", format: "a4" });
  const c: Ctx = { pdf, y: PAGE.margin + 8 };

  // Cover
  coverPage(c, {
    candidate: resume.name,
    role: jobDescription.jobTitle,
    domain: jobDescription.domain,
    matchPct,
    analysisId,
    generatedAt,
  });

  // Executive Summary
  const summaryText =
    `${resume.name} is a ${resume.currentDesignation} at ${resume.currentCompany} with ${resume.experience} of overall experience. ` +
    `The candidate matches ${matching.similarity.matchedRequiredSkills} of ${matching.similarity.totalRequiredSkills} required skills for the ${jobDescription.jobTitle} role in ${jobDescription.domain}. ` +
    `Recommendation: ${recommendationFor(matchPct).label}.`;
  const highlights = [
    `Overall Match Score: ${matchPct}%`,
    `Matching Skills: ${matching.matchingSkills.length}`,
    `Missing Skills: ${matching.missingSkills.length}`,
    `Additional Skills: ${matching.additionalSkills.length}`,
    `Seniority: ${jobDescription.seniorityLevel}`,
  ];
  executiveSummaryPage(c, summaryText, highlights);

  candidateProfilePage(c, resume);
  skillAnalysisPage(c, matching);
  evidenceAnalysisPage(c, evidence);
  pipelineTransparencyPage(c, metadata);

  // Header on every page + footers
  const total = pdf.getNumberOfPages();
  for (let i = 1; i <= total; i++) {
    pdf.setPage(i);
    drawHeader(pdf, resume.name);
  }
  drawFooters(pdf, generatedAt);

  return pdf;
}

export function downloadRecruiterReportPdf(result: PipelineResult): void {
  const pdf = generateRecruiterReportPdf(result);
  if (!result.ok) return;
  pdf.save(buildRecruiterReportFileName(result.resume.name));
}